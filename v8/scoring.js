function calculateResult(answers) {
  if (!Array.isArray(answers) || answers.length !== questions.length || !questions.every((q,i) => Number.isInteger(answers[i]) && q.options[answers[i]])) throw new Error('请完整回答全部 ' + questions.length + ' 道题。');
  const scores = {F:0,M:0,L:0,S:0,D:0,A:0,O:0,J:0};
  questions.forEach((q,i) => { scores[q.options[answers[i]].score]++; });
  const axisCode = dimensions.map(d => {
    if (scores[d.left] === scores[d.right]) throw new Error('维度题数配置错误：不应出现同分。');
    return scores[d.left] > scores[d.right] ? d.left : d.right;
  }).join('');
  const personality = personalities.find(p => p.code === axisCode);
  if (!personality) throw new Error('缺少四维组合对应的人格。');
  return {scores, axisCode, personality};
}
